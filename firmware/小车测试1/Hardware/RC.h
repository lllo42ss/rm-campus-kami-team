#ifndef __RC_H
#define __RC_H

#include "stm32f10x.h"

/* ============================================================
 *  遥控接收机（PWM 通道型）
 *
 *  航模遥控器 + 接收机，接收机每个通道一根信号线，输出 1000~2000us 的
 *  方波：1500us 是中位，1000us 一头，2000us 另一头。
 *
 *  接线（最多 4 通道）：
 *      ch1 -> PB0
 *      ch2 -> PB3
 *      ch3 -> PA12
 *      ch4 -> PA15
 *  接收机的 VCC 从 TB6612 模块的 5V 取，GND 必须和主控共地。
 *
 *  注意：接收机信号线电平一般是 3.3V；老式 5V 输出的接收机直接接
 *  这几个脚有风险，量一下信号幅度再插。
 *
 *  ------------------------------------------------------------
 *  如果你的接收机不是这种"一线一通道"的：
 *    · PPM 汇总输出（一根线传所有通道）——告诉我，改读取函数就行
 *    · SBUS（串口 100000 波特率 8E2，信号反相）——需要加一个反相电路
 *    · 蓝牙串口模块 / 手柄接收器 —— 是另一套写法
 *  这三种都要改本文件，别硬套。
 * ============================================================ */

void    RC_Init(void);
void    RC_Update(void);                /* 1ms 调用，负责失控判断 */
float   RC_GetUs(uint8_t ch);           /* 原始脉宽，微秒；0 = 还没收到 */
float   RC_GetNorm(uint8_t ch);         /* 归一到 -1.0 ~ +1.0，带死区 */
uint8_t RC_IsConnected(void);           /* 1 = 接收机有信号 */

#endif
