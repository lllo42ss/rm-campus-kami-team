#ifndef __TESTMODE_H
#define __TESTMODE_H

#include "stm32f10x.h"

/* ============================================================
 *  考察模式：一键跑某个考察动作，用完就走
 *
 *  用板上的 Key1（PB1）操作：
 *      短按          进考察模式 / 切到下一项
 *      长按(>0.8s)   退出考察模式
 *
 *  五个动作，正好对着完整形态考察的评分表：
 *      1  直线移动 5m（走够距离自动停，用编码器里程计判断）
 *      2  原地旋转 720 度（转够角度自动停）
 *      3  全向平移 2m
 *      4  枪口俯仰 45~135 度来回（行程 90 度，要求 >30 度）
 *      5  波箱连发 10 秒
 *
 *  没有按钮的话，用一根杜邦线把 PB1 和 GND 碰一下，就相当于短按
 * ============================================================ */

void    TestMode_Init(void);
void    TestMode_Update(void);      /* 1ms 调用 */
uint8_t TestMode_IsActive(void);    /* 1 = 正在考察模式（调试屏显示用） */
uint8_t TestMode_GetItem(void);     /* 当前是第几项，0~4 */

#endif
